class IdCheck(typing.NamedTuple):
    """Result of comparing IDREGISTER with the ids the unit reports (ExportDataItems)."""
    checked: int
    # IDREGISTER key -> (table ids, id the unit reports)
    changed: typing.Dict[str, typing.Tuple[typing.List[int], int]]
    # IDREGISTER key -> id the unit reports, for registers the table lacks
    missing: typing.Dict[str, int]

    @property
    def ok(self) -> bool:
        return not self.changed and not self.missing


def check_idregister(items) -> IdCheck:
    """Compare exported data items (id + extension.modbusRegister) with IDREGISTER."""
    changed, missing, checked = {}, {}, 0
    for item in items:
        ext = item.get("extension") or {}
        if item.get("id") is None or ext.get("modbusRegister") is None:
            continue
        checked += 1
        key = str(ext["modbusRegister"] + 1)
        table = IDREGISTER.get(key)
        ids = table if isinstance(table, list) else [] if table is None else [table]
        if item["id"] in ids:
            continue
        if ids:
            changed[key] = (ids, item["id"])
        else:
            missing[key] = item["id"]
    return IdCheck(checked, changed, missing)


def register_ids(check: typing.Optional[IdCheck] = None) -> typing.List[int]:
    """Ids for a full read: IDREGISTER, corrected by a check against the unit."""
    ids = {x for val in IDREGISTER.values() for x in (val if isinstance(val, list) else [val])}
    if check is not None:
        for table_ids, live_id in check.changed.values():
            if len(table_ids) == 1:
                ids.discard(table_ids[0])  # with several ids it is unclear which one moved; keep them
            ids.add(live_id)
        ids.update(check.missing.values())
    return sorted(ids)
